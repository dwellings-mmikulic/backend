// Package server exposes the Roku Search feed, the public listings API, and
// a health endpoint.
package server

import (
	"context"
	"encoding/json"
	"log/slog"
	"net/http"
	"time"

	httpSwagger "github.com/swaggo/http-swagger"

	_ "github.com/dwellingtw/backend/docs" // swagger spec, generated by `make swagger`
	"github.com/dwellingtw/backend/internal/api"
	"github.com/dwellingtw/backend/internal/feed"
	"github.com/dwellingtw/backend/internal/property"
)

// feedSource provides the fixed set of listings the Roku Search feed carries.
type feedSource interface {
	ListSearchFeed(ctx context.Context) ([]property.Property, error)
}

// feedCacheControl lets Bunny and browsers hold the feed for five minutes.
const feedCacheControl = "public, max-age=300"

// Server is the HTTP server of the api role.
type Server struct {
	repo feedSource
	log  *slog.Logger
	now  func() time.Time
	srv  *http.Server
	mux  *http.ServeMux
}

// New creates a Server bound to addr (e.g. ":8080"). publicAPI may be nil
// (e.g. in tests that only exercise the feed).
func New(addr string, repo feedSource, publicAPI *api.API, log *slog.Logger) *Server {
	s := &Server{
		repo: repo,
		log:  log,
		now:  time.Now,
	}
	mux := http.NewServeMux()
	s.mux = mux
	mux.HandleFunc("GET /roku/search-feed.json", s.handleSearchFeed)
	mux.HandleFunc("GET /healthz", s.handleHealth)
	mux.Handle("GET /swagger/", httpSwagger.WrapHandler)
	if publicAPI != nil {
		publicAPI.Register(mux)
	}
	s.srv = &http.Server{
		Addr:              addr,
		Handler:           mux,
		ReadHeaderTimeout: 10 * time.Second,
	}
	return s
}

// Mounter registers routes on a mux (e.g. linear.Handler).
type Mounter interface {
	Register(mux *http.ServeMux)
}

// Mount adds routes. Call before Start.
func (s *Server) Mount(m Mounter) { m.Register(s.mux) }

// Start runs the HTTP server until it errors or is shut down.
func (s *Server) Start() error {
	if err := s.srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
		return err
	}
	return nil
}

// Shutdown gracefully stops the server.
func (s *Server) Shutdown(ctx context.Context) error {
	return s.srv.Shutdown(ctx)
}

// handleSearchFeed serves the Roku Search feed: a fixed set of published
// listings (see property.ListSearchFeed) in the catalogue format Roku ingests
// for its home-screen search, all on one page with no nextPageUrl. Query
// parameters are ignored, so old paged URLs get the same page. The Roku app
// itself reads /api/v1/properties, not this.
func (s *Server) handleSearchFeed(w http.ResponseWriter, r *http.Request) {
	props, err := s.repo.ListSearchFeed(r.Context())
	if err != nil {
		s.log.Error("search feed query failed", "error", err)
		writeFeedError(w, http.StatusInternalServerError, "internal error")
		return
	}
	doc := feed.BuildSearch(props, s.now())

	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", feedCacheControl)
	if err := json.NewEncoder(w).Encode(doc); err != nil {
		s.log.Error("search feed encode failed", "error", err)
	}
}

func writeFeedError(w http.ResponseWriter, status int, msg string) {
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(map[string]string{"error": msg})
}

func (s *Server) handleHealth(w http.ResponseWriter, _ *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	_, _ = w.Write([]byte(`{"status":"ok"}`))
}
